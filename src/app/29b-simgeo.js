/* ---------- SIMGEO (v0.44): физические отметки для расчёта, независимые от отображения ----------
   Расчёт (гидравлика HYDX) не читает сцену: видимость моделей, положение групп, userData. Иначе результат зависел бы от того,
   какая модель показана (слой «Модели склада»), и от того, успели ли загрузиться модели (до v0.44 — так и было:
   отметка зеркала в РВС смещалась на 0,135 м, в РГС — на 0,014 м).
   Отметки — по размерам детальных моделей РВС-1000 (RVSD) и РГС-75 (RGSD) и посадке объектов на рельеф при регистрации (o.baseY).
   Визуализация уровня в разрезе резервуара (procSim) по-прежнему подстраивается под показанную модель — это отображение, не расчёт. */
const SIMGEO = (() => {
  const objOf = id => { const o = OBJ.find(q => q.id === id); if (!o) throw new Error('SIMGEO: нет объекта ' + id); return o; };
  const CAR = { R: 1.5, AX: 2.55 };   // котёл вагона-цистерны: радиус и ось над головкой рельса (модель вагона — условно, тип не указан)
  return {
    CAR,
    rvsBottom: id => objOf(id).baseY + RVSD.Y_BOT,             // днище РВС-1000
    rgsAxis: id => objOf(id).baseY + RGSD.AXIS,                 // ось РГС-75
    carBottom: i => EST177.carPos[i][1] + CAR.AX - CAR.R,        // низ котла вагона на позиции эстакады i
    ground: (x, z) => hAt(x, z),                                 // отметка рельефа
  };
})();
